export async function seedPlayersAF() {
  console.log('👤 Seeding players — Groups A-F...');
  let total = 0;

  for (const [code, players] of Object.entries(SQUADS)) {
    const team = await prisma.team.findUnique({ where: { code } });
    if (!team) { console.warn(`  ⚠ Team ${code} not found, skipping`); continue; }

    for (const [name, shortName, position, number, club, clubCountry, born, height] of players) {
      await prisma.player.upsert({
        where: { teamId_number: { teamId: team.id, number } },
        update: { name, shortName, position, club, clubCountry, height, nationality: team.name, birthDate: new Date(born) },
        create: { name, shortName, position, number, club, clubCountry, height, nationality: team.name, birthDate: new Date(born), teamId: team.id, isActive: true },
      });
      total++;
    }
    console.log(`  ✅ ${code} — ${players.length} jugadores`);
  }

  console.log(`✅ Groups A-F: ${total} jugadores insertados`);
}
